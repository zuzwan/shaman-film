#!/usr/bin/env python3
"""Generate assets/sprites/rig.yaml: the rig at wide-shot size.

Per the world bible: a salvaged machine shaped and worshipped as a totem.
Two columns of seven carved face-housings (one storage cell each) bolted to a
salvaged mast with riveted steel bands; a copper coil and antenna on top;
cables looping down the side; a crank wheel and clamp leads at the foot.
Auk's rig: 14 slots, 12 filled, 2 blank (bottom right, raw pale wood).

    python tools/art/rig.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from raster import Canvas, write_sprite  # noqa: E402

W, H = 23, 42
CX = 10  # mast centre

# carved faces, 7 wide x 3 tall: brow row, eye row, mouth row. 'E' = eye.
# Each one is a different animal, crude and blocky: wolf, bear, elk, cat, boar, hare, owl-less moth...
FACES = [
    ["T.WWW.T", "WEWWWEW", "WWWMWWW"],   # wolf: ears up
    [".WWWWW.", "WEWWWEW", "WMMMMMW"],   # bear: wide mouth
    ["H.WWW.H", "WEWWWEW", ".WWMWW."],   # elk: antler stubs
    ["T.WWW.T", "WWEWEWW", "WWMMMWW"],   # cat: close eyes
    [".WWWWW.", "EWWWWWE", "WMMWMMW"],   # boar: tusks
    ["TT...TT", "WEWWWEW", ".WWMWW."],   # hare: long ears
    ["WWWWWWW", "WEEWEEW", "WWWMWWW"],   # moth: big eyes
]
BLANK = [".PPPPP.", "PPPPPPP", "PPPPPPP"]


def build(eyes="dark", flare=False, crank=0):
    c = Canvas(W, H)
    eye_col = {"dark": "ink0", "lit": "ember1", "lit2": "ember2"}[eyes]
    # antenna and copper coil
    c.line(CX, 0, CX, 7, "ash2")
    c.put(CX, 0, "ember2" if eyes != "dark" else "rust0")
    for y, half in ((3, 2), (5, 3), (7, 2)):
        c.line(CX - half, y, CX + half, y, "rust1")
        c.put(CX - half, y, "blood4")
    # mast behind everything
    c.rect(CX - 1, 8, 3, 30, "ink2")
    y = 9
    for i in range(7):
        # riveted steel band above each face row
        c.line(CX - 8, y, CX + 8, y, "ash1")
        for rx in (CX - 7, CX - 1, CX + 1, CX + 7):
            c.put(rx, y, "ash3")
        y += 1
        for side, x0 in ((0, CX - 8), (1, CX + 1)):
            face = BLANK if (side == 1 and i >= 5) else FACES[(i * 2 + side) % 7]
            for dy, row in enumerate(face):
                for dx, ch in enumerate(row):
                    wood = "rust1" if dx < 4 else "rust0"   # lit from the left
                    col = {"W": wood, "M": "ink0", "T": wood, "H": "ash3", "P": "ash3" if dx < 4 else "ash2",
                           "E": eye_col}.get(ch)
                    if col:
                        c.put(x0 + dx, y + dy, col)
            # carved brow highlight: top-left light catches the wood
            if face is not BLANK:
                c.put(x0 + 1, y, "blood4")
        y += 3
    c.line(CX - 8, y, CX + 8, y, "ash1")
    # the last blank face lights during a capture: glass showing through the raw wood
    if flare:
        fy = 9 + 6 * 4 + 1 + 1
        c.put(CX + 2, fy, "flame"); c.put(CX + 6, fy, "flame")
        c.line(CX + 3, fy + 1, CX + 5, fy + 1, "ember2")
    # cable loop down the left side, plugged into three bands
    for yy in range(12, 36):
        c.put(CX - 10 + (1 if yy % 8 < 4 else 0), yy, "ash0")
    c.line(CX - 9, 12, CX - 8, 12, "ink1"); c.line(CX - 9, 24, CX - 8, 24, "ink1")
    # foot: mast spike, base plate, crank wheel, clamp leads
    c.rect(CX - 1, y + 1, 3, 3, "ink2")
    c.line(CX - 3, H - 2, CX + 3, H - 2, "ink1")
    c.put(CX, H - 1, "ink1")
    wx, wy = CX + 7, y + 3
    c.ring(wx + 0.5, wy + 0.5, 2.6, "ash2")
    c.put(wx, wy, "ash3")
    hx, hy = [(wx + 2, wy - 2), (wx + 3, wy), (wx + 2, wy + 2), (wx, wy + 3)][crank % 4]
    c.line(wx, wy, hx, hy, "ash3")
    c.put(hx, hy, "rust1")
    # clamp leads hanging from the right edge
    c.line(CX + 9, 14, CX + 10, 26, "ink1")
    c.put(CX + 10, 27, "ash3"); c.put(CX + 11, 27, "ash3")
    c.outline("ink0")
    return c


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[2] / "assets/sprites/rig.yaml"
    write_sprite(out, "rig",
                 "# The rig at wide-shot size, generated by tools/art/rig.py (see its docstring).\n"
                 "# States: idle (dark; a dead rig is a carved pole), hum (charged: eyes glow),\n"
                 "# capture (the crank turns, the last blank face flares as it takes an animal).",
                 (CX, H - 1), 3,
                 {"idle": [build("dark")],
                  "hum": [build("lit"), build("lit2")],
                  "capture": [build("lit", True, 0), build("lit2", False, 1), build("lit", True, 2), build("lit2", True, 3)]})
    print(out)
