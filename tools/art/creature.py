#!/usr/bin/env python3
"""Generate assets/sprites/gaunt.yaml: the first creature, a wide-shot predator.

Appalachian horror register, not a named myth: a tall starved thing with a
stag's skull and antlers, arms to the ground, that walks like a man who has
forgotten how. "The gaunt" in the script. Faces right.

    python tools/art/creature.py

States: stalk (4 frames, long slow stride), idle (2, sways), lunge (2, arms
forward, head down), rear (1, full height, antlers spread: the standoff beat).
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from raster import Canvas, write_sprite  # noqa: E402

W, H = 30, 46
PAD = (2, 6)  # the frame is embedded in a 34x52 canvas so antlers and the lunge clear the edges


def build(pose="idle", f=0):
    c = Canvas(W, H)
    sway = math.sin(f * math.pi / 2) if pose in ("idle", "stalk") else 0
    # pose parameters
    if pose == "rear":
        hx, hy, lean = 14, 4, 0
    elif pose == "lunge":
        hx, hy, lean = 19, 14 + f * 2, 6
    else:
        hx, hy, lean = 12 + int(sway), 8, 2
    spine = [(hx, hy + 6), (hx - lean + 2, 22), (10, 32)]
    # legs: long, backward-bent, the stride from f
    if pose == "stalk":
        a = [(-5, 2), (2, 6), (6, 2), (-2, -3)][f % 4]
        legs = [((10, 32), (10 + a[0], 40), (12 + a[0] - 2, 45)), ((11, 32), (12 + a[1], 39), (14 + a[1], 45))]
    elif pose == "lunge":
        legs = [((10, 32), (4, 38), (0, 45)), ((11, 32), (16, 40), (20, 45))]
    else:
        legs = [((10, 32), (7, 39), (6, 45)), ((11, 32), (14, 39), (15, 45))]
    for (x0, y0), (x1, y1), (x2, y2) in legs:
        c.line(x0, y0, x1, y1, "ink1"); c.line(x0 + 1, y0, x1 + 1, y1, "ink1")
        c.line(x1, y1, x2, y2, "ink1")
        c.put(x2, y2, "ash0"); c.put(x2 + 1, y2, "ash0")   # hoof-like feet
    # ribs: a starved torso, ribs showing as lighter ticks
    c.poly([(hx - 3, hy + 6), (hx + 3, hy + 7), (hx - lean + 5, 23), (hx - lean - 1, 23)], "ink1",
           shade=("ink0", "ink1", (1, 0)))
    for i in range(4):
        y = hy + 10 + i * 3
        c.put(hx - 1 - i // 2, y, "ash0"); c.put(hx + 1 - i // 2, y, "ash0")
    c.poly([(hx - lean - 1, 23), (hx - lean + 5, 23), (13, 33), (8, 33)], "ink1")
    # arms: too long, hanging past the knees; forward in a lunge
    if pose == "lunge":
        arms = [((hx - 2, hy + 8), (hx + 7, hy + 4), (hx + 12, hy + 7)), ((hx, hy + 9), (hx + 8, hy + 9), (hx + 13, hy + 13))]
    elif pose == "rear":
        arms = [((hx - 2, hy + 8), (hx - 10, hy + 2), (hx - 13, hy - 4)), ((hx + 2, hy + 8), (hx + 10, hy + 2), (hx + 13, hy - 4))]
    else:
        s = int(sway * 2)
        arms = [((hx - 2, hy + 8), (hx - 5 + s, 24), (hx - 6 + s, 36)), ((hx + 2, hy + 8), (hx + 5 - s, 25), (hx + 7 - s, 37))]
    for (x0, y0), (x1, y1), (x2, y2) in arms:
        c.line(x0, y0, x1, y1, "ink1"); c.line(x1, y1, x2, y2, "ink1")
        for k in range(3):  # fingers
            c.put(x2 + (k - 1), y2 + 1 + (k % 2), "ash0")
    # the skull: bone, a long muzzle, black sockets
    c.poly([(hx - 3, hy), (hx + 2, hy - 1), (hx + 8, hy + 2), (hx + 9, hy + 4), (hx + 4, hy + 5), (hx - 2, hy + 6), (hx - 4, hy + 3)], "ash3",
           shade=("ash2", "bone", (0.4, -1)))
    c.put(hx, hy + 2, "ink0"); c.put(hx + 1, hy + 2, "ink0")  # socket
    c.put(hx + 6, hy + 4, "ink0")                              # nostril
    if pose == "lunge" or pose == "rear":
        c.put(hx, hy + 2, "ember2")                            # the socket catches light
    # antlers: branching up and out from the skull
    for side in (-1, 1):
        bx, by = hx + (2 if side > 0 else -2), hy - 1
        c.line(bx, by, bx + side * 4, by - 6, "ash2")
        c.line(bx + side * 4, by - 6, bx + side * 8, by - 8, "ash2")
        c.line(bx + side * 2, by - 3, bx + side * 1, by - 7, "ash2")
        c.line(bx + side * 5, by - 6, bx + side * 5, by - 10, "ash2")
        c.put(bx + side * 8, by - 8, "ash3"); c.put(bx + side * 5, by - 10, "ash3"); c.put(bx + side, by - 7, "ash3")
    c.outline("ink0")
    big = Canvas(W + 2 * PAD[0], H + PAD[1])
    for y in range(H):
        for x in range(W):
            if c.px[y][x]:
                big.put(x + PAD[0], y + PAD[1], c.px[y][x])
    return big


if __name__ == "__main__":
    out = Path(__file__).resolve().parents[2] / "assets/sprites/gaunt.yaml"
    write_sprite(out, "gaunt",
                 "# The gaunt: a starved, antlered walker, wide-shot size. Generated by tools/art/creature.py.\n"
                 "# Faces right. stalk is slow (fps 3); lunge and rear are the attack and the standoff.",
                 (12 + PAD[0], 45 + PAD[1]), 3,
                 {"idle": [build("idle", 0), build("idle", 2)],
                  "stalk": [build("stalk", i) for i in range(4)],
                  "lunge": [build("lunge", 0), build("lunge", 1)],
                  "rear": [build("rear")]})
    print(out)
