GLYPHS = {}
for ch, spec in _G.items():
    rows = spec.split("/")
    w = max(len(r) for r in rows)
    g = np.zeros((H, w), dtype=bool)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            g[y, x] = c == "#"
    GLYPHS[ch] = g


def width(text):
    w = 0
    for ch in text:
        w += SPACE + 1 if ch == " " else GLYPHS.get(ch, GLYPHS["?"]).shape[1] + 1
    return max(0, w - 1)


def text_mask(text):
    m = np.zeros((H, max(1, width(text))), dtype=bool)
    x = 0
    for ch in text:
        if ch == " ":
            x += SPACE + 1
            continue
        g = GLYPHS.get(ch, GLYPHS["?"])
        m[:, x:x + g.shape[1]] = g
        x += g.shape[1] + 1
    return m


def wrap(text, max_px):
    """Greedy word wrap to a pixel width."""
    lines, cur = [], ""
    for word in text.split():
        trial = f"{cur} {word}".strip()
        if cur and width(trial) > max_px:
            lines.append(cur)
            cur = word
        else:
            cur = trial
    return lines + ([cur] if cur else [])
